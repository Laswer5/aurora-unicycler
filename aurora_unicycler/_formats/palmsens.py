    """Device-specific MethodSCRIPT capabilities used by the exporter."""

    device: PalmSensDevice
    display_name: str
    min_voltage_v: float
    max_voltage_v: float
    max_abs_current_ma: float
    max_peis_amplitude_v: float
    max_peis_frequency_hz: float
    max_geis_frequency_hz: float
    supports_geis: bool
    measurement_variables: tuple[MeasurementVariable, ...]


